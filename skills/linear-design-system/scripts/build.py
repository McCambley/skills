#!/usr/bin/env python3
"""Build the Vector design system's CSS and gallery from its sources.

Usage: python3 build.py [--check]

Reads tokens.json, src/components.css, src/gallery.html and icons/*.svg, and writes:

  dist/tokens.css    CSS custom properties only: light on :root, dark under
                     prefers-color-scheme and [data-theme="dark"]
  dist/vector.css    tokens + type classes + components + icon classes
  dist/gallery.html  a self-contained page showing every token, type style,
                     component and icon, with a light/dark toggle

Before writing, it checks the sources: every var(--x) the CSS uses must be
defined, and the text, link, accent and icon colours must meet their contrast
targets in both themes. Any failure exits 1 and writes nothing.

--check only verifies: the sources pass, and dist/ matches what a build would
write. Use it to confirm nobody hand-edited dist/.
"""
import html
import json
import pathlib
import re
import sys
import urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
FONTS = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
         '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
         '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;550;600'
         '&family=JetBrains+Mono:wght@400&display=swap">')
# Custom properties the component CSS sets itself rather than taking from tokens.json.
LOCAL_VARS = {"tile"}


def css_value(v):
    m = re.fullmatch(r"\{([A-Za-z0-9_.-]+)\}", str(v))
    return f"var(--{m.group(1)})" if m else str(v)


def theme_values(tokens):
    """{token: (light, dark)} with {ref} values resolved, for contrast checks."""
    first = tokens["color"]["themes"][0]["id"]
    raw = {}
    for t in tokens["color"]["tokens"]:
        v = t["value"]
        raw[t["name"]] = (v.get("light", v.get(first)), v.get("dark", v.get(first))) if isinstance(v, dict) else (v, v)
    def res(v, i):
        m = re.fullmatch(r"\{([A-Za-z0-9_.-]+)\}", str(v))
        return res(raw[m.group(1)][i], i) if m else v
    return {k: (res(l, 0), res(d, 1)) for k, (l, d) in raw.items()}


def build_tokens(tokens):
    first = tokens["color"]["themes"][0]["id"]
    light, dark, common = [], [], []
    for t in tokens["color"]["tokens"]:
        v = t["value"]
        lv, dv = (v.get("light", v.get(first)), v.get("dark", v.get(first))) if isinstance(v, dict) else (v, v)
        if lv == dv:
            common.append(f"--{t['name']}:{css_value(lv)};")
        else:
            light.append(f"--{t['name']}:{css_value(lv)};")
            dark.append(f"--{t['name']}:{css_value(dv)};")
    for fam in ("spacing", "radius", "shadow"):
        for t in tokens.get(fam, {}).get("tokens", []):
            common.append(f"--{t['name']}:{t['value']};")
    for k, v in tokens["type"]["families"].items():
        common.append(f"--font-{k}:{v};")
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            n = s["name"]
            common.append(f"--t-{n}-size:{s['fontSize']}; --t-{n}-lh:{s['lineHeight']}; "
                          f"--t-{n}-weight:{s['fontWeight']}; --t-{n}-track:{s.get('letterSpacing', 'normal')};")
    return "\n".join([
        f"/* {tokens.get('name', 'Vector')} tokens v{tokens.get('version', '?')}. Generated by scripts/build.py from tokens.json. */",
        ":root{color-scheme:light;", *("  " + x for x in common + light), "}",
        '@media (prefers-color-scheme: dark){ :root:not([data-theme="light"]){color-scheme:dark;',
        *("  " + x for x in dark), "}}",
        ':root[data-theme="dark"]{color-scheme:dark;', *("  " + x for x in dark), "}"])


def build_type_classes(tokens):
    out = ["/* Type styles: class=\"vx-t-<name>\". Generated from tokens.json. */"]
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            n = s["name"]
            out.append(f".vx-t-{n}{{font-family:var(--font-{g['family']});font-size:var(--t-{n}-size);"
                       f"line-height:var(--t-{n}-lh);font-weight:var(--t-{n}-weight);letter-spacing:var(--t-{n}-track)"
                       + (";font-variant-ligatures:none" if g["family"] == "mono" else "") + "}")
    return "\n".join(out)


def icon_uri(svg_text):
    svg = re.sub(r"\s+", " ", svg_text.strip())
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe=" =:/,'-.")


def build_icons():
    rules = ["/* Icons: class=\"vx-ico vx-ico--<name>\". Generated from icons/*.svg. */"]
    for f in sorted((ROOT / "icons").glob("*.svg")):
        svg = f.read_text()
        if re.search(r"<script|\bon\w+=|href=|foreignObject", svg, re.I):
            sys.exit(f"icons/{f.name}: refusing an SVG with script, event handlers or links")
        rules.append(f'.vx-ico--{f.stem}{{background-image:url("{icon_uri(svg)}")}}')
    return "\n".join(rules)


# ---------- checks

def defined_vars(tokens):
    d = {t["name"] for t in tokens["color"]["tokens"]}
    for fam in ("spacing", "radius", "shadow"):
        d |= {t["name"] for t in tokens.get(fam, {}).get("tokens", [])}
    d |= {f"font-{k}" for k in tokens["type"]["families"]}
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            d |= {f"t-{s['name']}-{x}" for x in ("size", "lh", "weight", "track")}
    return d


def rgba(c):
    c = c.strip()
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            h = "".join(x * 2 for x in h)
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0
    m = re.fullmatch(r"rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)", c)
    if not m:
        raise ValueError(f"can't parse colour {c!r}")
    return float(m[1]), float(m[2]), float(m[3]), float(m[4] or 1)


def over(fg, bg):
    r, g, b, a = fg
    return tuple(a * x + (1 - a) * y for x, y in zip((r, g, b), bg[:3])) + (1.0,)


def lum(c):
    def ch(x):
        x /= 255
        return x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4
    r, g, b = c[:3]
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def ratio(fg, bg):
    a, b = sorted((lum(fg), lum(bg)), reverse=True)
    return (a + 0.05) / (b + 0.05)


def contrast_errors(tokens):
    v = theme_values(tokens)
    errs = []
    # (foreground tokens, background tokens, minimum ratio)
    rules = [
        (["text-primary", "text-secondary", "text-tertiary", "accent-text"], ["bg-base", "bg-raised", "bg-elevated"], 4.5),
        ([n for n in v if n.startswith("icon-")], ["bg-base"], 3.0),
        (["on-accent"], ["accent"], 4.5),
    ]
    # Reported but not enforced: hover is a passing state, and changing its colour is a design decision.
    warn_rules = [(["on-accent"], ["accent-hover"], 4.5)]
    warns = []
    for i, theme in enumerate(("light", "dark")):
        base = rgba(v["bg-base"][i])
        for fgs, bgs, need, out in [(*r, errs) for r in rules] + [(*r, warns) for r in warn_rules]:
            for bgn in bgs:
                bg = over(rgba(v[bgn][i]), base)
                for fgn in fgs:
                    r = ratio(over(rgba(v[fgn][i]), bg), bg)
                    if r < need:
                        out.append(f"{theme}: {fgn} on {bgn} is {r:.2f}:1, below {need}:1")
    return errs, warns


def check_vars(css, tokens, where):
    used = set(re.findall(r"var\(--([a-z0-9-]+)", css))
    missing = sorted(used - defined_vars(tokens) - LOCAL_VARS)
    return [f"{where} uses var(--{m}), which tokens.json doesn't define" for m in missing]


# ---------- gallery

def gallery(tokens, vector_css):
    tpl = (ROOT / "src" / "gallery.html").read_text()
    sw = []
    for t in tokens["color"]["tokens"]:
        v = t["value"]
        vals = (f"{v.get('dark')} · {v.get('light')}" if isinstance(v, dict) else str(v))
        sw.append(f'<div class="g-sw"><span class="g-chip" style="background:var(--{t["name"]})"></span>'
                  f'<div><code class="vx-t-mono">{t["name"]}</code><p class="vx-t-micro">{html.escape(t["usage"])}</p>'
                  f'<p class="vx-t-micro g-val">{html.escape(vals)}</p></div></div>')
    ty = []
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            ty.append(f'<div class="g-type"><code class="vx-t-mono">vx-t-{s["name"]}</code>'
                      f'<span class="vx-t-micro g-meta">{s["fontSize"]}/{s["lineHeight"]} · {s["fontWeight"]}</span>'
                      f'<div class="vx-t-{s["name"]}">{html.escape(s.get("sample", s["name"]))}</div></div>')
    ic = []
    for f in sorted((ROOT / "icons").glob("*.svg")):
        ic.append(f'<div class="g-icon"><span class="vx-ico vx-ico--{f.stem}" aria-hidden="true"></span>'
                  f'<span class="vx-ico vx-ico--lg vx-ico--{f.stem}" aria-hidden="true"></span>'
                  f'<code class="vx-t-mono">{f.stem}</code></div>')
    out = (tpl.replace("<!-- @fonts -->", FONTS)
              .replace("/* @vector */", "/* @vector:start */\n" + vector_css.rstrip("\n") + "\n/* @vector:end */")
              .replace("<!-- @swatches -->", "\n".join(sw))
              .replace("<!-- @type -->", "\n".join(ty))
              .replace("<!-- @icons -->", "\n".join(ic))
              .replace("{{VERSION}}", str(tokens.get("version", "?"))))
    left = re.findall(r"<!-- @\w+ -->|/\* @vector \*/|\{\{[A-Z]+\}\}", out)
    if left:
        sys.exit("src/gallery.html has unfilled placeholders: " + ", ".join(left))
    return out


def main():
    check_only = "--check" in sys.argv
    tokens = json.loads((ROOT / "tokens.json").read_text())
    components = (ROOT / "src" / "components.css").read_text().strip()
    gallery_src = (ROOT / "src" / "gallery.html").read_text()

    errs = check_vars(components, tokens, "src/components.css")
    errs += check_vars(gallery_src, tokens, "src/gallery.html")
    c_errs, c_warns = contrast_errors(tokens)
    errs += c_errs
    for w in c_warns:
        print("WARN  " + w)
    if errs:
        print("\n".join("ERROR " + e for e in errs))
        sys.exit(1)

    tok = build_tokens(tokens)
    vector = "\n\n".join([
        f"/* Vector design system v{tokens.get('version', '?')}: tokens, type, components and icons.\n"
        "   Generated by scripts/build.py. Don't edit; change the sources and rebuild.\n"
        "   Load the fonts separately with the <link> tags in SKILL.md. */",
        tok, build_type_classes(tokens), components, build_icons()]) + "\n"
    outputs = {
        DIST / "tokens.css": tok + "\n",
        DIST / "vector.css": vector,
        DIST / "gallery.html": gallery(tokens, vector),
    }
    if check_only:
        stale = [p.name for p, s in outputs.items() if not p.exists() or p.read_text() != s]
        if stale:
            print("STALE dist/" + ", dist/".join(stale) + ": run scripts/build.py")
            sys.exit(1)
        print(f"OK: sources pass and dist/ is current ({len(defined_vars(tokens))} tokens).")
        return
    DIST.mkdir(exist_ok=True)
    for p, s in outputs.items():
        p.write_text(s)
    n_icons = len(list((ROOT / "icons").glob("*.svg")))
    print(f"OK: {len(defined_vars(tokens))} tokens, {n_icons} icons, contrast passes in both themes.")
    print("wrote " + ", ".join(f"dist/{p.name} ({len(s) // 1024} KB)" for p, s in outputs.items()))


if __name__ == "__main__":
    main()
